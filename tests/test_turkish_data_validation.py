# ---------------------------------------------------------------- formatters

class TestFormatters:
    def test_format_money(self):
        assert tdv.format_money(1250.5) == "1.250,50 ₺"
        assert tdv.format_money(1000000) == "1.000.000,00 ₺"
        assert tdv.format_money(0) == "0,00 ₺"
        assert tdv.format_money(-42.1) == "-42,10 ₺"

    def test_parse_money(self):
        assert tdv.parse_money("1.250,50") == 1250.5
        assert tdv.parse_money("1.250,50 ₺") == 1250.5
        assert tdv.parse_money("42,10") == 42.1

    def test_money_round_trip(self):
        for amount in (0, 9.99, 1250.5, 1234567.89):
            assert tdv.parse_money(tdv.format_money(amount)) == amount

    def test_format_date_tr(self):
        assert tdv.format_date_tr("2026-11-18") == "18.11.2026"

    def test_tr_case(self):
        assert tdv.tr_upper("istanbul") == "İSTANBUL"
        assert tdv.tr_upper("diyarbakır") == "DİYARBAKIR"
        assert tdv.tr_lower("İSTANBUL") == "istanbul"
        assert tdv.tr_lower("IĞDIR") == "ığdır"
        # The classic trap: English rules give ISTANBUL / istanbul.
        assert tdv.tr_upper("istanbul") != "ISTANBUL"
        assert tdv.tr_lower("ISTANBUL") != "istanbul"


