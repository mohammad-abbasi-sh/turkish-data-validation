"""Tests for turkish_data_validation.py — every check code, every
formatter, CLI exit codes, and the CSV audit path.

Test numbers are either published examples (TCKN 10000000146 and
IBAN TR33 0006 1005 1978 6457 8413 26 appear in Turkish validator
documentation; VKN 1234567890 and 4540536920 are the examples
used by turkish_kit / turkiye-mcp) or numbers generated by the
tool's own generate_* functions and re-validated — never a real
person's or company's identifier.
"""
import json
import subprocess
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).parent.parent
                       / "skills" / "turkish-data-validation" / "scripts"))
import turkish_data_validation as tdv

HERE = Path(__file__).parent
TOOL = (HERE.parent / "skills" / "turkish-data-validation" / "scripts"
        / "turkish_data_validation.py")
FIXTURE_CSV = HERE / "fixtures" / "mixed-tr.csv"


def run_cli(*args, input_text=None):
    return subprocess.run(
        [sys.executable, str(TOOL), *args],
        input=input_text, capture_output=True, text=True, timeout=60)


# ---------------------------------------------------------------- TDV-01 TCKN

class TestTckn:
    def test_canonical_example_valid(self):
        assert tdv.validate_tckn("10000000146")["valid"] is True

    def test_wrong_11th_digit(self):
        res = tdv.validate_tckn("10000000145")
        assert res["valid"] is False
        assert "11th digit" in res["reason"]

    def test_wrong_10th_digit(self):
        # 10000000146 with the 10th digit changed 4 -> 5.
        res = tdv.validate_tckn("10000000156")
        assert res["valid"] is False
        assert "10th digit" in res["reason"]

    def test_leading_zero(self):
        assert tdv.validate_tckn("00000000146")["valid"] is False

    def test_wrong_length(self):
        assert tdv.validate_tckn("1000000014")["valid"] is False
        assert tdv.validate_tckn("100000001460")["valid"] is False

    def test_non_digits(self):
        assert tdv.validate_tckn("1000000014a")["valid"] is False

    def test_spaces_and_dashes_stripped(self):
        assert tdv.validate_tckn("1000 0000 146")["valid"] is True

    def test_check_digits(self):
        assert tdv.tckn_check_digits("100000001") == (4, 6)

    def test_generate_round_trip(self):
        for seed in (1, 2, 3, 42, 2026):
            n = tdv.generate_tckn(seed)
            assert tdv.validate_tckn(n)["valid"] is True
            assert len(n) == 11 and n[0] != "0"
        assert tdv.generate_tckn(42) == tdv.generate_tckn(42)


