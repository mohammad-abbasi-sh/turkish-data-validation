class TestDetect:
    def test_detect_tckn(self):
        assert detect_ok("10000000146", "tckn")

    def test_detect_vkn(self):
        assert detect_ok("1234567890", "vkn")

    def test_detect_iban(self):
        assert detect_ok("TR33 0006 1005 1978 6457 8413 26", "iban")

    def test_detect_mobile_with_trunk(self):
        assert detect_ok("0532 123 45 67", "phone")

    def test_detect_mobile_bare(self):
        assert detect_ok("5321234567", "phone")

    def test_detect_plate(self):
        assert detect_ok("34 AB 123", "plate")

    def test_detect_postal(self):
        assert detect_ok("34000", "postal")

    def test_detect_unknown(self):
        res = tdv.detect("hello world")
        assert res["valid"] is False
        assert res["kind"] == "unknown"


def detect_ok(value, kind):
    res = tdv.detect(value)
    return res["valid"] is True and res["kind"] == kind


# ---------------------------------------------------------------- CLI

class TestCli:
    def test_validate_exit_0(self):
        proc = run_cli("validate", "tckn", "10000000146")
        assert proc.returncode == 0
        assert "[VALID]" in proc.stdout

    def test_validate_exit_1(self):
        proc = run_cli("validate", "tckn", "10000000145")
        assert proc.returncode == 1
        assert "[INVALID]" in proc.stdout

    def test_validate_json(self):
        proc = run_cli("validate", "iban",
                       "TR330006100519786457841326", "--json")
        assert proc.returncode == 0
        data = json.loads(proc.stdout)
        assert data["valid"] is True
        assert data["detail"]["bank_code"] == "00061"

    def test_detect_cli(self):
        proc = run_cli("detect", "34 AB 123")
        assert proc.returncode == 0
        assert "plate" in proc.stdout

    def test_format_cli(self):
        assert run_cli("format", "money", "1250.5").stdout.strip() == \
            "1.250,50 ₺"
        assert run_cli("format", "upper", "istanbul").stdout.strip() == \
            "İSTANBUL"
        assert run_cli("format", "date", "2026-11-18").stdout.strip() == \
            "18.11.2026"

    def test_generate_cli(self):
        proc = run_cli("generate", "tckn", "--seed", "42")
        assert proc.returncode == 0
        assert tdv.validate_tckn(proc.stdout.strip())["valid"] is True

    def test_usage_error_exit_2(self):
        proc = run_cli("validate", "tckn")
        assert proc.returncode == 2

    def test_audit_fixture(self):
        proc = run_cli("audit", str(FIXTURE_CSV), "--column", "tckn")
        assert proc.returncode == 1
        assert "5 rows, 3 valid, 2 invalid" in proc.stdout
        assert "row 4" in proc.stdout  # bad checksum
        assert "row 6" in proc.stdout  # wrong length

    def test_audit_json(self):
        proc = run_cli("audit", str(FIXTURE_CSV), "--column", "tckn",
                       "--json")
        summary = json.loads(proc.stdout)
        assert summary["rows"] == 5
        assert summary["valid"] == 3
        assert summary["invalid"] == 2
        assert summary["findings"][0]["row"] == 4
