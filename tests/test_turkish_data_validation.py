# ---------------------------------------------------------------- TDV-03 IBAN

class TestIban:
    def test_published_example_valid(self):
        res = tdv.validate_iban("TR33 0006 1005 1978 6457 8413 26")
        assert res["valid"] is True
        assert res["detail"]["formatted"] == \
            "TR33 0006 1005 1978 6457 8413 26"
        assert res["detail"]["bank_code"] == "00061"
        assert res["detail"]["reserved_digit"] == "0"
        assert res["detail"]["account_part"] == "0519786457841326"

    def test_unknown_bank_code_is_warning_not_error(self):
        res = tdv.validate_iban("TR330006100519786457841326")
        assert res["valid"] is True
        assert res["detail"]["bank"] is None
        assert any("not in the TCMB" in w for w in res["warnings"])

    def test_known_bank_named(self):
        iban = tdv.generate_iban(seed=5, bank_code="00062")
        res = tdv.validate_iban(iban)
        assert res["valid"] is True
        assert res["detail"]["bank"] == \
            "Türkiye Garanti Bankası A.Ş. (Garanti BBVA)"

    def test_wrong_check_digits(self):
        assert tdv.validate_iban("TR320006100519786457841326")["valid"] \
            is False

    def test_wrong_country(self):
        assert tdv.validate_iban("DE89370400440532013000")["valid"] \
            is False

    def test_wrong_length(self):
        assert tdv.validate_iban("TR3300061005197864578413")["valid"] \
            is False

    def test_lowercase_and_spaces_accepted(self):
        assert tdv.validate_iban("tr33 0006 1005 1978 6457 8413 26")["valid"] \
            is True

    def test_format_iban(self):
        assert tdv.format_iban("TR330006100519786457841326") == \
            "TR33 0006 1005 1978 6457 8413 26"

    def test_generate_round_trip(self):
        for seed in (1, 2, 3):
            iban = tdv.generate_iban(seed=seed)
            assert tdv.validate_iban(iban)["valid"] is True
            assert iban.startswith("TR")
        assert tdv.generate_iban(seed=9) == tdv.generate_iban(seed=9)

    def test_generate_unknown_bank_rejected(self):
        with pytest.raises(ValueError):
            tdv.generate_iban(bank_code="99999")

    def test_check_digits_function(self):
        # BBAN of the published example: check digits must be 33.
        assert tdv.iban_check_digits("0006100519786457841326") == "33"


# ---------------------------------------------------------------- TDV-04 phone

class TestPhone:
    @pytest.mark.parametrize("value", [
        "+90 532 123 45 67", "0532 123 45 67", "00905321234567",
        "905321234567", "5321234567", "(0532) 123 45 67",
    ])
    def test_mobile_forms(self, value):
        res = tdv.validate_phone(value)
        assert res["valid"] is True, value
        assert res["detail"]["kind_detail"] == "mobile"
        assert res["detail"]["e164"] == "+905321234567"
        assert res["detail"]["formatted"] == "(0532) 123 45 67"

    def test_landline_istanbul(self):
        res = tdv.validate_phone("0212 123 45 67")
        assert res["valid"] is True
        assert res["detail"]["kind_detail"] == "landline"
        assert res["detail"]["city"] == "İstanbul (Avrupa)"
        assert res["detail"]["formatted"] == "(0212) 123 45 67"

    def test_landline_ankara(self):
        res = tdv.validate_phone("+90 312 123 45 67")
        assert res["valid"] is True
        assert res["detail"]["city"] == "Ankara"

    def test_landline_unverified_area_is_warning(self):
        # 0284 is Edirne's real area code — deliberately outside
        # the conservative verified list, so it warns, not fails.
        res = tdv.validate_phone("0284 123 45 67")
        assert res["valid"] is True
        assert res["detail"]["city"] is None
        assert any("not in the verified list" in w
                   for w in res["warnings"])

    def test_444_number(self):
        res = tdv.validate_phone("444 1 234")
        assert res["valid"] is True
        assert res["detail"]["kind_detail"] == "444 service number"

    def test_0850_number(self):
        res = tdv.validate_phone("0850 305 12 34")
        assert res["valid"] is True
        assert res["detail"]["kind_detail"] == "0850/0800 service number"

    def test_short_number(self):
        assert tdv.validate_phone("112")["valid"] is True
        assert tdv.validate_phone("155")["valid"] is True

    def test_too_short(self):
        assert tdv.validate_phone("0532 123 45 6")["valid"] is False

    def test_landline_starting_with_1(self):
        assert tdv.validate_phone("0123 456 78 90")["valid"] is False


